impl ParametricSection for ZSection {
    fn build(&self) -> Section {
        // Similar to channel but with flanges on opposite sides
        let h = self.height;
        let b = self.flange_width;
        let s = self.web_thickness;
        let t = self.flange_thickness;
        let lip = self.lip_length;

        let hh = h / 2.0;

        let mut vertices = Vec::new();

        // Start bottom left
        vertices.push(Point::new(0.0, -hh));
        vertices.push(Point::new(s, -hh));
        vertices.push(Point::new(s, -hh + t));
        if lip > 0.0 {
            vertices.push(Point::new(s + b, -hh + t));
            vertices.push(Point::new(s + b, -hh));
            vertices.push(Point::new(s + lip, -hh));
            vertices.push(Point::new(s + lip, -hh + t));
            vertices.push(Point::new(s + b, -hh + t));
        } else {
            vertices.push(Point::new(s + b, -hh + t));
        }

        // Web
        vertices.push(Point::new(s + b, hh - t));

        // Top flange - on opposite side
        if lip > 0.0 {
            vertices.push(Point::new(s + b, hh - t));
            vertices.push(Point::new(s + b, hh));
            vertices.push(Point::new(s + lip, hh));
            vertices.push(Point::new(s + lip, hh - t));
        }
        vertices.push(Point::new(s, hh - t));
        vertices.push(Point::new(s, hh));
        vertices.push(Point::new(0.0, hh));
        vertices.push(Point::new(0.0, -hh));

        let mut clean = Vec::new();
        for v in vertices {
            if clean.last() != Some(&v) {
                clean.push(v);
            }
        }
        if clean.len() > 1 && clean[0] == clean[clean.len() - 1] {
            clean.pop();
        }

        let outer = Polygon::new(clean);
        Section::new(outer, Vec::new())
    }

    fn designation(&self) -> String {
        format!(
            "Z {:.0}x{:.0}x{:.1}x{:.1}",
            self.height * 1000.0,
            self.flange_width * 1000.0,
            self.web_thickness * 1000.0,
            self.flange_thickness * 1000.0
        )
    }
}

/// Built-up section: multiple sections combined.
#[derive(Debug, Clone)]
pub struct BuiltUpSection {
    pub components: Vec<(Box<dyn ParametricSection>, Point, Material)>, // section, offset, material
}

impl BuiltUpSection {
    pub fn new() -> Self {
        Self {
            components: Vec::new(),
        }
    }

    pub fn add(
        mut self,
        section: impl ParametricSection + 'static,
        offset: Point,
        material: Material,
    ) -> Self {
        self.components.push((Box::new(section), offset, material));
        self
    }

    pub fn build(&self) -> crate::section_library::CompositeSection {
        // Build all components and combine
        let mut all_polygons = Vec::new();
        let mut material_groups = Vec::new();
        let mut current_index = 0;

        for (section, offset, material) in &self.components {
            let built = section.build();
            // Apply offset
            let mut outer = built.outer;
            for v in &mut outer.vertices {
                v.x += offset.x;
                v.y += offset.y;
            }
            let mut holes = built.holes;
            for h in &mut holes {
                for v in &mut h.vertices {
                    v.x += offset.x;
                    v.y += offset.y;
                }
            }
            all_polygons.push(outer);
            all_polygons.extend(holes);
            material_groups.push(crate::material::MaterialGroup::new(
                material.clone(),
                (current_index..current_index + 1 + built.holes.len()).collect(),
            ));
            current_index += 1 + built.holes.len();
        }

        // For simplicity, just use first polygon as outer, rest as holes
        // In reality, we'd need boolean union operations
        crate::section_library::CompositeSection::new(
            all_polygons[0].clone(),
            all_polygons[1..].to_vec(),
            material_groups,
        )
    }
}

impl Default for BuiltUpSection {
    fn default() -> Self {
        Self::new()
    }
}

