impl ParametricSection for TeeSection {
    fn build(&self) -> Section {
        let h = self.height;
        let b = self.flange_width;
        let s = self.web_thickness;
        let t = self.flange_thickness;

        let hw = b / 2.0;
        let hh = h / 2.0;
        let sw = s / 2.0;

        // CCW polygon tracing the T-section material boundary.
        // Flange at top, web extends downward from flange centre.
        let vertices = vec![
            Point::new(-hw, hh),     // flange top-left
            Point::new(hw, hh),      // flange top-right
            Point::new(hw, hh - t),  // flange bottom-right
            Point::new(sw, hh - t),  // web top-right
            Point::new(sw, -hh),     // web bottom-right
            Point::new(-sw, -hh),    // web bottom-left
            Point::new(-sw, hh - t), // web top-left
            Point::new(-hw, hh - t), // flange bottom-left
        ];

        let outer = Polygon::new(vertices);
        Section::new(outer, Vec::new())
    }

    fn designation(&self) -> String {
        format!(
            "T {:.0}x{:.0}x{:.1}x{:.1}",
            self.height * 1000.0,
            self.flange_width * 1000.0,
            self.web_thickness * 1000.0,
            self.flange_thickness * 1000.0
        )
    }
}

/// Rectangular Hollow Section (RHS / SHS / Box section).
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct RectangularHollowSection {
    pub width: f64,
    pub height: f64,
    pub thickness: f64,
    pub outer_radius: f64,
    pub inner_radius: f64,
}

impl RectangularHollowSection {
    pub fn new(
        width: f64,
        height: f64,
        thickness: f64,
        outer_radius: f64,
        inner_radius: f64,
    ) -> Self {
        assert!(width > 0.0 && height > 0.0, "Dimensions must be positive");
        assert!(thickness > 0.0, "Thickness must be positive");
        assert!(
            2.0 * thickness < width.min(height),
            "Thickness too large for dimensions"
        );
        Self {
            width,
            height,
            thickness,
            outer_radius,
            inner_radius,
        }
    }

    pub fn square(side: f64, thickness: f64) -> Self {
        Self::new(side, side, thickness, 0.0, 0.0)
    }

    pub fn from_designation(designation: &str) -> Option<Self> {
        // Format: "SHS100X100X5" or "RHS200X100X6"
        let upper = designation.to_uppercase();
        if upper.starts_with("SHS") || upper.starts_with("RHS") {
            let rest = &upper[3..];
            let parts: Vec<&str> = rest.split('X').collect();
            if parts.len() == 3 {
                let w = parts[0].parse::<f64>().ok()?;
                let h = parts[1].parse::<f64>().ok()?;
                let t = parts[2].parse::<f64>().ok()?;
                // Assume radius = 1.5 * t for hot-formed, 2*t for cold-formed
                let r_out = 1.5 * t;
                let r_in = r_out - t;
                return Some(Self::new(
                    w / 1000.0,
                    h / 1000.0,
                    t / 1000.0,
                    r_out / 1000.0,
                    r_in / 1000.0,
                ));
            }
        }
        None
    }
}

impl ParametricSection for RectangularHollowSection {
    fn build(&self) -> Section {
        let w = self.width;
        let h = self.height;
        let t = self.thickness;
        let r_out = self.outer_radius;
        let r_in = self.inner_radius;

        if r_out > 0.0 {
            // Rounded corners
            let outer = rounded_rectangle_polygon(w, h, r_out, 8);
            let inner = rounded_rectangle_polygon(w - 2.0 * t, h - 2.0 * t, r_in, 8);
            Section::new(outer, vec![inner])
        } else {
            // Sharp corners
            let outer = rectangle_polygon(w, h);
            let inner = rectangle_polygon(w - 2.0 * t, h - 2.0 * t);
            Section::new(outer, vec![inner])
        }
    }

    fn designation(&self) -> String {
        if (self.width - self.height).abs() < 1e-9 {
            format!(
                "SHS {:.0}x{:.0}",
                self.width * 1000.0,
                self.thickness * 1000.0
            )
        } else {
            format!(
                "RHS {:.0}x{:.0}x{:.0}",
                self.width * 1000.0,
                self.height * 1000.0,
                self.thickness * 1000.0
            )
        }
    }
}

/// Circular Hollow Section (CHS).
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct CircularHollowSectionLib {
    pub outer_diameter: f64,
    pub wall_thickness: f64,
    pub n_vertices: usize,
}

impl CircularHollowSectionLib {
    pub fn new(outer_diameter: f64, wall_thickness: f64) -> Self {
        Self::with_vertices(outer_diameter, wall_thickness, 64)
    }

    pub fn from_designation(designation: &str) -> Option<Self> {
        // Format: "CHS60X3" (outer diameter [mm] x wall thickness [mm])
        let upper = designation.to_uppercase();
        let rest = upper.strip_prefix("CHS")?.trim_start_matches('Ø');
        let parts: Vec<&str> = rest.split('X').collect();
        if parts.len() != 2 {
            return None;
        }
        let d = parts[0].parse::<f64>().ok()? / 1000.0;
        let t = parts[1].parse::<f64>().ok()? / 1000.0;
        if d <= 0.0 || t <= 0.0 || 2.0 * t >= d {
            return None;
        }
        Some(Self::new(d, t))
    }

    pub fn with_vertices(outer_diameter: f64, wall_thickness: f64, n_vertices: usize) -> Self {
        assert!(outer_diameter > 0.0, "Diameter must be positive");
        assert!(wall_thickness > 0.0, "Thickness must be positive");
        assert!(
            2.0 * wall_thickness < outer_diameter,
            "Wall thickness too large"
        );
        assert!(n_vertices >= 8, "At least 8 vertices");
        Self {
            outer_diameter,
            wall_thickness,
            n_vertices,
        }
    }
}

impl ParametricSection for CircularHollowSectionLib {
    fn build(&self) -> Section {
        use crate::section_library::hollow_circle_polygon;
        let ro = self.outer_diameter / 2.0;
        let ri = ro - self.wall_thickness;
        let (outer, inner) = hollow_circle_polygon(ro, ri, self.n_vertices);
        Section::new(outer, vec![inner])
    }

    fn designation(&self) -> String {
        format!(
            "CHS Ø{:.0}x{:.1}",
            self.outer_diameter * 1000.0,
            self.wall_thickness * 1000.0
        )
    }
}

/// Z-section (Z-purlin).
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct ZSection {
    pub height: f64,
    pub flange_width: f64,
    pub web_thickness: f64,
    pub flange_thickness: f64,
    pub lip_length: f64,
}

impl ZSection {
    pub fn new(
        height: f64,
        flange_width: f64,
        web_thickness: f64,
        flange_thickness: f64,
        lip_length: f64,
    ) -> Self {
        assert!(
            height > 0.0 && flange_width > 0.0,
            "Dimensions must be positive"
        );
        assert!(
            web_thickness > 0.0 && flange_thickness > 0.0,
            "Thicknesses must be positive"
        );
        Self {
            height,
            flange_width,
            web_thickness,
            flange_thickness,
            lip_length,
        }
    }
}

impl ParametricSection for ZSection {
    fn build(&self) -> Section {
        // Similar to channel but with flanges on opposite sides
        let h = self.height;
        let b = self.flange_width;
        let s = self.web_thickness;
        let t = self.flange_thickness;
        let lip = self.lip_length;

        let hh = h / 2.0;

        // Z-section: top flange extends LEFT from web, bottom flange extends RIGHT.
        // Web: x ∈ [0, s], y ∈ [-hh, hh]
        // Top flange: x ∈ [-b, 0], y ∈ [hh-t, hh]
        // Bottom flange: x ∈ [s, s+b], y ∈ [-hh, -hh+t]
        // CCW outline starting from top-left outer corner.
        let mut vertices = Vec::new();

        vertices.push(Point::new(-b, hh));
        vertices.push(Point::new(0.0, hh));
        vertices.push(Point::new(s, hh));
        vertices.push(Point::new(s, -hh + t));
        if lip > 0.0 {
            vertices.push(Point::new(s + b - t, -hh + t));
            vertices.push(Point::new(s + b - t, -hh + t + lip));
            vertices.push(Point::new(s + b, -hh + t + lip));
        } else {
            vertices.push(Point::new(s + b, -hh + t));
        }
        vertices.push(Point::new(s + b, -hh));
        vertices.push(Point::new(s, -hh));
        vertices.push(Point::new(0.0, -hh));
        vertices.push(Point::new(0.0, hh - t));
        if lip > 0.0 {
            vertices.push(Point::new(-b + t, hh - t));
            vertices.push(Point::new(-b + t, hh - t - lip));
            vertices.push(Point::new(-b, hh - t - lip));
        } else {
            vertices.push(Point::new(-b, hh - t));
        }

        let mut clean = Vec::new();
        for v in vertices {
            if clean.last() != Some(&v) {
                clean.push(v);
            }
        }
        if clean.len() > 1 && clean[0] == clean[clean.len() - 1] {
            clean.pop();
        }

        let outer = Polygon::new(clean);
        Section::new(outer, Vec::new())
    }

    fn designation(&self) -> String {
        format!(
            "Z {:.0}x{:.0}x{:.1}x{:.1}",
            self.height * 1000.0,
            self.flange_width * 1000.0,
            self.web_thickness * 1000.0,
            self.flange_thickness * 1000.0
        )
    }
}

